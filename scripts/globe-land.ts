// Regenerates src/app/data/globe-land.ts, the land mask the landing hero's
// globe draws: `bun scripts/globe-land.ts`.
//
// The globe needs one bit per grid cell, not country outlines, so this samples
// world-110m.json once here instead of shipping it (195 KB) and d3-geo to every
// visitor of the landing page.
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";
import type { GeometryCollection, Topology } from "topojson-specification";
import { globeGrid } from "../src/app/lib/globe-grid";

const topology: Topology<{ countries: GeometryCollection }> = await Bun.file(
  "src/app/data/world-110m.json",
).json();
const land = feature(topology, topology.objects.countries);

const bits: boolean[] = [];
for (const [lon, lat] of globeGrid()) {
  bits.push(land.features.some((country) => geoContains(country, [lon, lat])));
}
const bytes = new Uint8Array(Math.ceil(bits.length / 8));
bits.forEach((on, i) => {
  if (on) bytes[i >> 3] |= 1 << (i & 7);
});

await Bun.write(
  "src/app/data/globe-land.ts",
  `// Generated by scripts/globe-land.ts from world-110m.json. Do not edit.
// One bit per cell of globeGrid (src/app/lib/globe-grid.ts), set where the
// cell's centre is on land. ${bits.filter(Boolean).length} of ${bits.length} cells.
export const GLOBE_LAND =
  "${Buffer.from(bytes).toString("base64")}";
`,
);
